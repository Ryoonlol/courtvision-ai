import type { ReactNode } from 'react'
import { ShieldCheck, Sparkles, Wrench } from 'lucide-react'
import type { AIResponse } from '../lib/types'
import { Pill, Skeleton } from './ui'

/** Frame for every Gemini-generated insight: shows provenance, grounding and fallback notices. */
export function AIPanel<T>({ title, res, loading, error, children }: {
  title: string
  res: AIResponse<T> | null
  loading: boolean
  error?: Error | null
  children: (data: T) => ReactNode
}) {
  return (
    <div className="gemini-glow rounded-2xl p-5">
      <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center gap-2">
          <span className="flex h-7 w-7 items-center justify-center rounded-lg bg-gemini/15 text-gemini"><Sparkles size={16} /></span>
          <div className="font-display text-lg font-semibold tracking-wide">{title}</div>
        </div>
        {res && (
          <div className="flex flex-wrap items-center gap-1.5">
            {res.source === 'gemini' ? (
              <Pill tone="gemini" title="Generated by Google Gemini from CourtVision's computed statistics">
                <Sparkles size={11} /> Gemini · {res.model}{res.cached ? ' · cached' : ''}
              </Pill>
            ) : (
              <Pill tone="warn" title={res.notice ?? ''}><Wrench size={11} /> Rule-based fallback</Pill>
            )}
            {res.grounding && (
              <Pill tone={res.grounding.passed ? 'good' : 'warn'} title={res.grounding.ungrounded.length ? `Unverified: ${res.grounding.ungrounded.join(', ')}` : 'Every number cited matches the computed data'}>
                <ShieldCheck size={11} /> {res.grounding.numbers_checked} numbers grounded
              </Pill>
            )}
          </div>
        )}
      </div>
      {loading && (
        <div className="space-y-2">
          <div className="text-xs text-gemini">Gemini is analyzing the computed projections…</div>
          <Skeleton className="h-5 w-2/3" />
          <Skeleton className="h-4 w-full" />
          <Skeleton className="h-4 w-5/6" />
        </div>
      )}
      {error && !loading && <div className="text-sm text-bad">{error.message}</div>}
      {res && !loading && (
        <>
          {res.notice && <div className="mb-3 rounded-lg border border-warn/30 bg-warn/5 px-3 py-2 text-xs text-warn">{res.notice}</div>}
          {children(res.data)}
        </>
      )}
    </div>
  )
}
